#!/usr/bin/env python3
"""Fix stale grading_check.json and preserve T85 regraded ring record."""

import shutil
import json
import hashlib
import subprocess
from pathlib import Path

BLADE_DIR = Path("/work/datagen_keepbl/runs/tistos_s1_0131/blade")
OLD_JSON = BLADE_DIR / "grading_check.json"
SAVED_JSON = BLADE_DIR / "grading_check_graded_ring.json"
CANONICAL_VTK = BLADE_DIR / "blocks_blade.vtk"
GRADED_VTK = BLADE_DIR / "blocks_blade_graded.vtk"
V1_VTK = BLADE_DIR / "blocks_blade_v1.vtk"
SIDECAR = BLADE_DIR / "grading_check_inputs.txt"

# Step 1: Copy current grading_check.json to grading_check_graded_ring.json
print(f"[1/4] Copying {OLD_JSON} -> {SAVED_JSON}")
shutil.copyfile(OLD_JSON, SAVED_JSON)

# Step 2: Add "describes" note to the saved copy
print(f"[2/4] Adding 'describes' note to {SAVED_JSON}")
with open(SAVED_JSON, 'r') as f:
    data = json.load(f)
data['describes'] = 'regraded ring (T85), not the canonical blocks_blade.vtk'
with open(SAVED_JSON, 'w') as f:
    json.dump(data, f, indent=2)

# Step 3: Compute md5sums of the VTK files
print(f"[3/4] Computing md5sums...")
md5s = {}
for vtk_file in [CANONICAL_VTK, GRADED_VTK, V1_VTK]:
    if vtk_file.exists():
        md5 = hashlib.md5(vtk_file.read_bytes()).hexdigest()
        md5s[str(vtk_file.name)] = md5
        print(f"  {vtk_file.name}: {md5}")
    else:
        print(f"  WARNING: {vtk_file.name} does not exist")
        md5s[str(vtk_file.name)] = "MISSING"

# Write sidecar with md5 mapping
with open(SIDECAR, 'w') as f:
    f.write("# MD5 checksums of VTK files used by grading_check.py\n")
    f.write("# Generated by T92 fix_stale_grading_check.py\n\n")
    for name, md5 in md5s.items():
        f.write(f"{md5}  {name}\n")
    f.write("\n")
    f.write("# Mapping:\n")
    f.write(f"#   blocks_blade.vtk (canonical, on disk) = {md5s.get('blocks_blade.vtk', 'MISSING')}\n")
    f.write(f"#   blocks_blade_v1.vtk (original, pre-T85) = {md5s.get('blocks_blade_v1.vtk', 'MISSING')}\n")
    f.write(f"#   blocks_blade_graded.vtk (T85 regraded) = {md5s.get('blocks_blade_graded.vtk', 'MISSING')}\n")
    f.write(f"\n# Note: blocks_blade.vtk and blocks_blade_v1.vtk are identical (canonical, thin side = core)\n")
    f.write(f"#       blocks_blade_graded.vtk is the T85 regraded version (thin side = blade)\n")

print(f"  Wrote {SIDECAR}")

# Step 4: Run grading_check.py to regenerate grading_check.json from canonical mesh
print(f"[4/4] Running grading_check.py on canonical blocks_blade.vtk...")
worktree = Path("/opt/stack/dp3d_keep_bl/.micromanager/worktrees/job-20261030-133532-3225--T92")
grading_script = worktree / "experimentell/hex3d_algohex/grading_check.py"
result = subprocess.run(
    ["python3", str(grading_script), "--run-dir", str(BLADE_DIR.parent)],
    check=True,
    capture_output=True,
    text=True,
    cwd=str(worktree)
)
print("grading_check.py output:")
print(result.stdout)
if result.stderr:
    print("stderr:", result.stderr)

# Verify the new JSON
print("\n[Verification] Loading new grading_check.json...")
with open(OLD_JSON, 'r') as f:
    new_data = json.load(f)

print(f"  verdict: {new_data.get('verdict', 'N/A')}")
print(f"  thin_end_is: {new_data.get('thin_end_is', 'N/A')}")
print(f"  gap_ratio: {new_data.get('gap_ratio', 'N/A')}")

print("\nDone.")
